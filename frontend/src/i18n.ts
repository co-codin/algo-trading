export function normalizeLocale(value: string | null | undefined): Locale {
  return value === "zh" ? value : "en";
}

export function translate(locale: Locale, key: MessageKey): string {
  return messages[locale][key] ?? messages.en[key] ?? key;
}

export function translateStrategyTitle(
  locale: Locale,
  name: string,
  fallback: string,
): string {
  return strategyTitles[locale][name] ?? strategyTitles.en[name] ?? fallback;
}

export function translateStrategyDescription(
  locale: Locale,
  name: string,
  fallback: string,
): string {
  return strategyDescriptions[locale][name] ?? strategyDescriptions.en[name] ?? fallback;
}
